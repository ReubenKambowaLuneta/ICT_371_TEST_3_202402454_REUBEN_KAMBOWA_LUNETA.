CREATE OR REPLACE FUNCTION fn_water_charge(p_units numeric)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_units IS NULL OR p_units < 0 THEN RAISE EXCEPTION 'Consumption must be non-negative'; END IF;
 RETURN (LEAST(p_units,10)*5 + GREATEST(p_units-10,0)*8)::numeric(12,2);
END $$;

CREATE OR REPLACE FUNCTION trg_reading_validate_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.current_reading < NEW.previous_reading THEN RAISE EXCEPTION 'Current meter reading cannot be below previous reading'; END IF;
 RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_reading_validate ON readings;
CREATE TRIGGER trg_reading_validate BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION trg_reading_validate_fn();

CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id bigint, p_due_on date)
LANGUAGE plpgsql AS $$
DECLARE v_previous numeric; v_current numeric;
BEGIN
 SELECT previous_reading, current_reading INTO v_previous, v_current FROM readings WHERE reading_id = p_reading_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading %', p_reading_id; END IF;
 IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date is required'; END IF;
 INSERT INTO bills(reading_id, charge, amount_paid, due_on)
 VALUES(p_reading_id, fn_water_charge(v_current - v_previous), 0, p_due_on)
 -- FIX 3: This is the line that was killing your 2nd run
 ON CONFLICT (reading_id) DO NOTHING;
END $$;

CREATE OR REPLACE VIEW v_overdue_bills AS
 SELECT c.full_name, b.due_on, b.charge - b.amount_paid AS outstanding_amount
 FROM bills b JOIN readings r USING(reading_id) JOIN customers c USING(customer_id)
 WHERE b.due_on < CURRENT_DATE AND b.amount_paid < b.charge;

CREATE INDEX IF NOT EXISTS idx_bills_due_unpaid ON bills(due_on) WHERE amount_paid < charge;

CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO receivable_snapshot(snapshot_date, total_due)
 SELECT CURRENT_DATE, COALESCE(SUM(charge - amount_paid),0) FROM bills WHERE amount_paid < charge
 ON CONFLICT(snapshot_date) DO UPDATE SET total_due = EXCLUDED.total_due;
END $$;

