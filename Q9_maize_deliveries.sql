CREATE TABLE IF NOT EXISTS farmers(farmer_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,farmer_number text UNIQUE NOT NULL,full_name text NOT NULL);
CREATE TABLE IF NOT EXISTS deliveries(
 delivery_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,farmer_id int NOT NULL REFERENCES farmers,
 grade char(1) NOT NULL CHECK(grade IN('A','B','C')),weight_kg numeric(12,2) NOT NULL CHECK(weight_kg>0),
 unit_rate numeric(8,2) NOT NULL,total_value numeric(14,2) NOT NULL,
 delivered_on date NOT NULL,is_paid boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS daily_purchases(purchase_date date PRIMARY KEY,total_weight numeric(14,2) NOT NULL,total_value numeric(14,2) NOT NULL);
