CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade text)
RETURNS numeric(8,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_grade IS NULL THEN RAISE EXCEPTION 'Grade is required'; END IF;
 CASE upper(p_grade)
  WHEN 'A' THEN RETURN 5.00;
  WHEN 'B' THEN RETURN 4.00;
  WHEN 'C' THEN RETURN 3.00;
  ELSE RAISE EXCEPTION 'Unsupported grade %',p_grade;
 END CASE;
END $$;

CREATE OR REPLACE FUNCTION trg_delivery_pricing_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN RAISE EXCEPTION 'Weight must be positive'; END IF;
 NEW.grade:=upper(NEW.grade);
 NEW.unit_rate:=fn_maize_rate(NEW.grade);
 NEW.total_value:=NEW.weight_kg*NEW.unit_rate;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_delivery_pricing ON deliveries;
CREATE TRIGGER trg_delivery_pricing BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION trg_delivery_pricing_fn();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(p_farmer_id int,p_grade text,p_weight numeric,p_date date)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN RAISE EXCEPTION 'Unknown farmer'; END IF;
 IF p_grade IS NULL OR upper(p_grade) NOT IN('A','B','C') OR p_weight IS NULL OR p_weight<=0 OR p_date IS NULL THEN RAISE EXCEPTION 'Invalid delivery input'; END IF;
 INSERT INTO deliveries(farmer_id,grade,weight_kg,unit_rate,total_value,delivered_on,is_paid)
 VALUES(p_farmer_id,upper(p_grade),p_weight,0,0,p_date,false);
END $$;

CREATE OR REPLACE VIEW v_farmer_amount_due AS
 SELECT f.farmer_number,f.full_name,COALESCE(sum(d.total_value) FILTER(WHERE d.is_paid=false),0) AS amount_due
 FROM farmers f LEFT JOIN deliveries d USING(farmer_id)
 GROUP BY f.farmer_id,f.farmer_number,f.full_name;
CREATE INDEX IF NOT EXISTS idx_deliveries_farmer_date ON deliveries(farmer_id,delivered_on);

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_day IS NULL THEN RAISE EXCEPTION 'Date is required'; END IF;
 INSERT INTO daily_purchases(purchase_date,total_weight,total_value)
 SELECT p_day,COALESCE(sum(weight_kg),0),COALESCE(sum(total_value),0)
 FROM deliveries WHERE delivered_on=p_day
 ON CONFLICT(purchase_date) DO UPDATE SET
 total_weight=EXCLUDED.total_weight,total_value=EXCLUDED.total_value;
END $$;

