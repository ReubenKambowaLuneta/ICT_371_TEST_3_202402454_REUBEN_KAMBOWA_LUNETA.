CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id int,p_as_of date)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due date;v_return date;v_end date;v_exists boolean;
BEGIN
 SELECT due_on,returned_on,true INTO v_due,v_return,v_exists FROM loans WHERE loan_id=p_loan_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan %',p_loan_id; END IF;
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date is required'; END IF;
 v_end:=LEAST(p_as_of,COALESCE(v_return,p_as_of));
 RETURN GREATEST(v_end-v_due,0)*2.00;
END $$;

CREATE OR REPLACE FUNCTION trg_loan_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
  INSERT INTO loan_audit(loan_id,old_returned_on,new_returned_on)
  VALUES(NEW.loan_id,OLD.returned_on,NEW.returned_on);
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_loan_audit ON loans;
CREATE TRIGGER trg_loan_audit AFTER UPDATE ON loans
FOR EACH ROW EXECUTE FUNCTION trg_loan_audit_fn();

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id int,p_returned_on date)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed date;v_returned date;
BEGIN
 SELECT borrowed_on,returned_on INTO v_borrowed,v_returned FROM loans
 WHERE loan_id=p_loan_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan %',p_loan_id; END IF;
 IF v_returned IS NOT NULL THEN RAISE EXCEPTION 'Loan % has already been returned',p_loan_id; END IF;
 IF p_returned_on IS NULL OR p_returned_on<v_borrowed THEN RAISE EXCEPTION 'Invalid return date'; END IF;
 UPDATE loans SET returned_on=p_returned_on,
 fine_amount=fn_loan_fine(p_loan_id,p_returned_on) WHERE loan_id=p_loan_id;
END $$;

CREATE OR REPLACE VIEW v_overdue_loans AS
 SELECT l.loan_id,b.title,l.borrower_name,l.due_on,
 fn_loan_fine(l.loan_id,CURRENT_DATE) AS fine_as_of_today
 FROM loans l JOIN books b USING(book_id)
 WHERE l.returned_on IS NULL AND l.due_on<CURRENT_DATE;
CREATE INDEX IF NOT EXISTS idx_loans_book_open ON loans(book_id) WHERE returned_on IS NULL;

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of date)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'Date is required'; END IF;
 INSERT INTO overdue_summary(snapshot_date,overdue_count,total_fine)
 SELECT p_as_of,count(*) FILTER(WHERE returned_on IS NULL AND due_on<p_as_of),
 COALESCE(sum(GREATEST(p_as_of-due_on,0)*2.00) FILTER(WHERE returned_on IS NULL),0)
 FROM loans
 ON CONFLICT(snapshot_date) DO UPDATE SET
 overdue_count=EXCLUDED.overdue_count,total_fine=EXCLUDED.total_fine;
END $$;

