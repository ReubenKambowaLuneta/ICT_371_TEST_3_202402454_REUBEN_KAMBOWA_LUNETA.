CREATE TABLE IF NOT EXISTS books(book_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title text NOT NULL);
CREATE TABLE IF NOT EXISTS loans(
 loan_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,book_id int NOT NULL REFERENCES books,
 borrower_name text NOT NULL,borrowed_on date NOT NULL,due_on date NOT NULL,
 returned_on date,fine_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK(fine_amount>=0),
 CHECK(due_on>=borrowed_on),CHECK(returned_on IS NULL OR returned_on>=borrowed_on)
);
CREATE TABLE IF NOT EXISTS loan_audit(
 audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,loan_id int NOT NULL REFERENCES loans,
 old_returned_on date,new_returned_on date,changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS overdue_summary(
 snapshot_date date PRIMARY KEY,overdue_count bigint NOT NULL,total_fine numeric(14,2) NOT NULL
);
