CREATE TABLE IF NOT EXISTS students(student_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_number text UNIQUE NOT NULL,full_name text NOT NULL);
CREATE TABLE IF NOT EXISTS rooms(room_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,room_number text UNIQUE NOT NULL,capacity int NOT NULL CHECK(capacity>0));
CREATE TABLE IF NOT EXISTS allocations(
 allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id int NOT NULL REFERENCES students,room_id int NOT NULL REFERENCES rooms,
 allocated_on date NOT NULL,released_on date,status text NOT NULL CHECK(status IN('ACTIVE','ENDED')),
 CHECK((status='ACTIVE' AND released_on IS NULL) OR (status='ENDED' AND released_on IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS occupancy_snapshot(
 snapshot_date date NOT NULL,room_id int NOT NULL REFERENCES rooms,
 occupied_beds int NOT NULL,free_beds int NOT NULL,
 PRIMARY KEY(snapshot_date,room_id)
);
