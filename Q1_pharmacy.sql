CREATE SCHEMA IF NOT EXISTS ict371_q1;
SET search_path = ict371_q1, public;

CREATE TABLE IF NOT EXISTS medicines (
 medicine_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 medicine_name text NOT NULL,
 unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
 stock_qty integer NOT NULL CHECK (stock_qty >= 0)
);
CREATE TABLE IF NOT EXISTS sales (
 sale_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 medicine_id integer NOT NULL REFERENCES medicines,
 quantity integer NOT NULL CHECK (quantity > 0),
 unit_price numeric(10,2) NOT NULL CHECK (unit_price > 0),
 sold_on date NOT NULL
);
CREATE TABLE IF NOT EXISTS stock_audit (
 audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 medicine_id integer NOT NULL REFERENCES medicines,
 old_qty integer NOT NULL, new_qty integer NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS daily_sales (
 sales_date date PRIMARY KEY, total_qty bigint NOT NULL, total_amount numeric(14,2) NOT NULL
);

