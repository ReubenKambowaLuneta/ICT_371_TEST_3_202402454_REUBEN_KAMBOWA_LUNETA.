CREATE SCHEMA IF NOT EXISTS ict371_q2;
SET search_path = ict371_q2, public;

CREATE TABLE IF NOT EXISTS students (
 student_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_number text NOT NULL UNIQUE, full_name text NOT NULL,
 fee_due numeric(12,2) NOT NULL CHECK(fee_due>=0)
);
CREATE TABLE IF NOT EXISTS payments (
 payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id int NOT NULL REFERENCES students,
 amount numeric(12,2) NOT NULL CHECK(amount>0), paid_on date NOT NULL
);
CREATE TABLE IF NOT EXISTS payment_audit (
 audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id bigint NOT NULL REFERENCES payments,
 student_id int NOT NULL REFERENCES students,
 amount numeric(12,2) NOT NULL, logged_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS daily_collections (
 collection_date date PRIMARY KEY,payment_count bigint NOT NULL,total_amount numeric(14,2) NOT NULL
);
