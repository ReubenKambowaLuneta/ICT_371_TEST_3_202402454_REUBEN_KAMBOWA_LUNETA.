CREATE OR REPLACE FUNCTION fn_fee_balance(p_student_id int)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due numeric(12,2); v_paid numeric(12,2);
BEGIN
 SELECT fee_due INTO v_due FROM students WHERE student_id=p_student_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student %',p_student_id; END IF;
 SELECT COALESCE(sum(amount),0) INTO v_paid FROM payments WHERE student_id=p_student_id;
 RETURN v_due-v_paid;
END $$;

CREATE OR REPLACE FUNCTION trg_payment_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO payment_audit(payment_id,student_id,amount)
 VALUES(NEW.payment_id,NEW.student_id,NEW.amount);
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_payment_audit ON payments;
CREATE TRIGGER trg_payment_audit AFTER INSERT ON payments
FOR EACH ROW EXECUTE FUNCTION trg_payment_audit_fn();

CREATE OR REPLACE PROCEDURE pr_receive_payment(p_student_id int,p_amount numeric,p_paid_on date)
LANGUAGE plpgsql AS $$
DECLARE v_balance numeric(12,2);
BEGIN
 IF p_amount IS NULL OR p_amount<=0 OR p_paid_on IS NULL THEN RAISE EXCEPTION 'Amount must be positive and date required'; END IF;
 PERFORM 1 FROM students WHERE student_id=p_student_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student %',p_student_id; END IF;
 v_balance:=fn_fee_balance(p_student_id);
 IF p_amount>v_balance THEN RAISE EXCEPTION 'Payment % exceeds outstanding balance %',p_amount,v_balance; END IF;
 INSERT INTO payments(student_id,amount,paid_on) VALUES(p_student_id,p_amount,p_paid_on);
END $$;

CREATE OR REPLACE VIEW v_fee_balances AS
 SELECT s.student_number,s.full_name,fn_fee_balance(s.student_id) AS outstanding_balance
 FROM students s WHERE fn_fee_balance(s.student_id)>0;
CREATE INDEX IF NOT EXISTS idx_payments_student_paid_on ON payments(student_id,paid_on);

CREATE OR REPLACE PROCEDURE pr_refresh_collections(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_day IS NULL THEN RAISE EXCEPTION 'Date is required'; END IF;
 INSERT INTO daily_collections(collection_date,payment_count,total_amount)
 SELECT p_day,count(*),COALESCE(sum(amount),0) FROM payments WHERE paid_on=p_day
 ON CONFLICT(collection_date) DO UPDATE SET
 payment_count=EXCLUDED.payment_count,total_amount=EXCLUDED.total_amount;
END $$;

