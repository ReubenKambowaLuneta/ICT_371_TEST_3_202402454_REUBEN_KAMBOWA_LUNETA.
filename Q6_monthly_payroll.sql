CREATE TABLE IF NOT EXISTS employees(
 employee_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL,
 basic_salary numeric(12,2) NOT NULL CHECK(basic_salary>=0),
 allowance numeric(12,2) NOT NULL CHECK(allowance>=0),
 deduction numeric(12,2) NOT NULL CHECK(deduction>=0),active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS payroll(
 payroll_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id int NOT NULL REFERENCES employees,pay_month date NOT NULL,
 gross_pay numeric(12,2) NOT NULL,net_pay numeric(12,2) NOT NULL,
 UNIQUE(employee_id,pay_month),CHECK(pay_month=date_trunc('month',pay_month)::date)
);
CREATE TABLE IF NOT EXISTS salary_audit(
 audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,employee_id int NOT NULL REFERENCES employees,
 old_salary numeric(12,2) NOT NULL,new_salary numeric(12,2) NOT NULL,
 changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
