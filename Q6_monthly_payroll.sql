CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id int)
RETURNS numeric(12,2) LANGUAGE plpgsql AS $$
DECLARE v_basic numeric;v_allow numeric;v_deduct numeric;v_net numeric;
BEGIN
 SELECT basic_salary,allowance,deduction INTO v_basic,v_allow,v_deduct
 FROM employees WHERE employee_id=p_employee_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee %',p_employee_id; END IF;
 v_net:=v_basic+v_allow-v_deduct;
 IF v_net<0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative'; END IF;
 RETURN v_net;
END $$;

CREATE OR REPLACE FUNCTION trg_salary_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.basic_salary IS DISTINCT FROM NEW.basic_salary THEN
  INSERT INTO salary_audit(employee_id,old_salary,new_salary)
  VALUES(NEW.employee_id,OLD.basic_salary,NEW.basic_salary);
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_salary_audit ON employees;
CREATE TRIGGER trg_salary_audit AFTER UPDATE ON employees
FOR EACH ROW EXECUTE FUNCTION trg_salary_audit_fn();

CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month date)
LANGUAGE plpgsql AS $$
DECLARE e record;v_gross numeric(12,2);v_net numeric(12,2);
BEGIN
 IF p_month IS NULL OR p_month<>date_trunc('month',p_month)::date THEN RAISE EXCEPTION 'p_month must be the first day of a month'; END IF;
 FOR e IN SELECT * FROM employees WHERE active LOOP
  v_gross:=e.basic_salary+e.allowance;
  v_net:=fn_net_pay(e.employee_id);
  INSERT INTO payroll(employee_id,pay_month,gross_pay,net_pay)
  VALUES(e.employee_id,p_month,v_gross,v_net)
  ON CONFLICT(employee_id,pay_month) DO NOTHING;
 END LOOP;
END $$;

CREATE OR REPLACE VIEW v_payroll_report AS
 SELECT e.full_name,p.pay_month,p.gross_pay,p.net_pay
 FROM payroll p JOIN employees e USING(employee_id);
CREATE INDEX IF NOT EXISTS idx_payroll_month ON payroll(pay_month);

