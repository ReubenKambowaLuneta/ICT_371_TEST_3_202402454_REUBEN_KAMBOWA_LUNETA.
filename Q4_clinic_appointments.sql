CREATE TABLE IF NOT EXISTS patients(patient_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL);
CREATE TABLE IF NOT EXISTS doctors(doctor_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name text NOT NULL);
CREATE TABLE IF NOT EXISTS appointments(
 appointment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id int NOT NULL REFERENCES patients,doctor_id int NOT NULL REFERENCES doctors,
 appointment_day date NOT NULL,slot_time time NOT NULL,
 status text NOT NULL CHECK(status IN('BOOKED','ATTENDED','CANCELLED')),
 CHECK(slot_time IN('09:00','10:00','11:00','12:00'))
);
CREATE TABLE IF NOT EXISTS clinic_summary(
 summary_date date PRIMARY KEY,booked_count bigint NOT NULL,attended_count bigint NOT NULL,cancelled_count bigint NOT NULL
);
