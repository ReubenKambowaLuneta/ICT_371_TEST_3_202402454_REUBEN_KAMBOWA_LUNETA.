CREATE OR REPLACE FUNCTION trg_appointment_clash_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status<>'CANCELLED' AND EXISTS(
  SELECT 1 FROM appointments a
  WHERE a.doctor_id=NEW.doctor_id AND a.appointment_day=NEW.appointment_day
    AND a.slot_time=NEW.slot_time AND a.status<>'CANCELLED'
    AND a.appointment_id IS DISTINCT FROM NEW.appointment_id
 ) THEN RAISE EXCEPTION 'Doctor already has a non-cancelled appointment in this slot'; END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_appointment_clash ON appointments;
CREATE TRIGGER trg_appointment_clash BEFORE INSERT OR UPDATE ON appointments
FOR EACH ROW EXECUTE FUNCTION trg_appointment_clash_fn();

CREATE OR REPLACE FUNCTION fn_daily_load(p_doctor_id int,p_day date)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_count bigint;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM doctors WHERE doctor_id=p_doctor_id) THEN RAISE EXCEPTION 'Unknown doctor %',p_doctor_id; END IF;
 SELECT count(*) INTO v_count FROM appointments
 WHERE doctor_id=p_doctor_id AND appointment_day=p_day AND status<>'CANCELLED';
 RETURN v_count;
END $$;

CREATE OR REPLACE PROCEDURE pr_book_appointment(p_patient_id int,p_doctor_id int,p_day date,p_slot time)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM patients WHERE patient_id=p_patient_id) THEN RAISE EXCEPTION 'Unknown patient'; END IF;
 IF NOT EXISTS(SELECT 1 FROM doctors WHERE doctor_id=p_doctor_id) THEN RAISE EXCEPTION 'Unknown doctor'; END IF;
 IF p_day IS NULL OR p_day<CURRENT_DATE THEN RAISE EXCEPTION 'Appointment date cannot be in the past'; END IF;
 IF p_slot NOT IN('09:00','10:00','11:00','12:00') THEN RAISE EXCEPTION 'Unsupported slot'; END IF;
 INSERT INTO appointments(patient_id,doctor_id,appointment_day,slot_time,status)
 VALUES(p_patient_id,p_doctor_id,p_day,p_slot,'BOOKED');
END $$;

CREATE OR REPLACE VIEW v_today_appointments AS
 SELECT a.appointment_id,p.full_name AS patient_name,d.full_name AS doctor_name,a.slot_time
 FROM appointments a JOIN patients p USING(patient_id) JOIN doctors d USING(doctor_id)
 WHERE a.appointment_day=CURRENT_DATE AND a.status='BOOKED';
CREATE INDEX IF NOT EXISTS idx_appointments_day_doctor ON appointments(appointment_day,doctor_id);
CREATE OR REPLACE PROCEDURE pr_refresh_clinic_summary(p_day date)
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO clinic_summary
 SELECT p_day,count(*) FILTER(WHERE status='BOOKED'),
 count(*) FILTER(WHERE status='ATTENDED'),count(*) FILTER(WHERE status='CANCELLED')
 FROM appointments WHERE appointment_day=p_day
 ON CONFLICT(summary_date) DO UPDATE SET
 booked_count=EXCLUDED.booked_count,attended_count=EXCLUDED.attended_count,
 cancelled_count=EXCLUDED.cancelled_count;
END $$;

