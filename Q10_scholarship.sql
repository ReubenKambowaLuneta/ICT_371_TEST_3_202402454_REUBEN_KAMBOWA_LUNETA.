CREATE OR REPLACE FUNCTION fn_scholarship_eligible(p_age int,p_income numeric,p_mark numeric)
RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
 IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL OR p_age<=0 OR p_income<0 OR p_mark<0 OR p_mark>100
 THEN RAISE EXCEPTION 'Invalid scholarship assessment input'; END IF;
 RETURN p_age BETWEEN 18 AND 25 AND p_income<=3000 AND p_mark>=70;
END $$;

CREATE OR REPLACE FUNCTION trg_decision_audit_fn()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status IS DISTINCT FROM NEW.status THEN
  INSERT INTO decision_audit(application_id,old_status,new_status)
  VALUES(NEW.application_id,OLD.status,NEW.status);
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_decision_audit ON applications;
CREATE TRIGGER trg_decision_audit AFTER UPDATE ON applications
FOR EACH ROW EXECUTE FUNCTION trg_decision_audit_fn();

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id bigint)
LANGUAGE plpgsql AS $$
DECLARE a record;v_eligible boolean;
BEGIN
 SELECT * INTO a FROM applications WHERE application_id=p_application_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application %',p_application_id; END IF;
 IF a.status<>'PENDING' THEN RAISE EXCEPTION 'Application % has already been assessed',p_application_id; END IF;
 v_eligible:=fn_scholarship_eligible(a.age_at_application,a.monthly_income,a.average_mark);
 UPDATE applications SET status=CASE WHEN v_eligible THEN 'APPROVED' ELSE 'REJECTED' END
 WHERE application_id=p_application_id;
END $$;

CREATE OR REPLACE VIEW v_approved_applicants AS
 SELECT s.student_number,s.full_name,a.average_mark,a.status
 FROM applications a JOIN students s USING(student_id) WHERE a.status='APPROVED';
CREATE INDEX IF NOT EXISTS idx_applications_status_submitted ON applications(status,submitted_on);

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql AS $$
DECLARE a record;
BEGIN
 FOR a IN SELECT application_id FROM applications WHERE status='PENDING' ORDER BY application_id LOOP
  CALL pr_assess_application(a.application_id);
 END LOOP;
END $$;

