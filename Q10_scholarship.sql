CREATE TABLE IF NOT EXISTS students(
 student_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_number text UNIQUE NOT NULL,full_name text NOT NULL
);
CREATE TABLE IF NOT EXISTS applications(
 application_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,student_id int NOT NULL REFERENCES students,
 age_at_application int NOT NULL CHECK(age_at_application>0),
 monthly_income numeric(12,2) NOT NULL CHECK(monthly_income>=0),
 average_mark numeric(5,2) NOT NULL CHECK(average_mark BETWEEN 0 AND 100),
 submitted_on date NOT NULL,status text NOT NULL CHECK(status IN('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE IF NOT EXISTS decision_audit(
 audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,application_id bigint NOT NULL REFERENCES applications,
 old_status text NOT NULL,new_status text NOT NULL,changed_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
